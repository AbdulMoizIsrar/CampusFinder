import { Router } from 'express';
import { itemImageUpload } from '../middleware/itemImage.js';
import * as ctrl from '../controllers/itemController.js';
import { requireAuth } from '../middleware/auth.js';
import { itemCreateRules, itemUpdateRules, itemListRules, mongoId, validated, allowQueryKeys } from '../middleware/validate.js';
import { maybeLimit, claimLimiter } from '../middleware/security.js';
const router = Router();
const listKeys = allowQueryKeys('page', 'limit', 'type', 'category', 'status', 'location', 'from', 'to', 'q', 'sort', 'fields');
router.use(requireAuth);
router.get('/mine', listKeys, itemListRules, validated, ctrl.mine);
router.get('/', listKeys, itemListRules, validated, ctrl.list);
router.post('/', itemImageUpload, itemCreateRules, validated, ctrl.create);
router.get('/:id', mongoId(), validated, ctrl.one);
router.get('/:id/private', mongoId(), validated, ctrl.privateDetails);
router.patch('/:id', mongoId(), itemImageUpload, itemUpdateRules, validated, ctrl.update);
router.delete('/:id', mongoId(), validated, ctrl.remove);
router.get('/:id/matches', mongoId(), validated, ctrl.matches);
router.post('/:id/claims', maybeLimit(claimLimiter), mongoId(), validated, ctrl.claim);
router.get('/:id/claims', mongoId(), validated, ctrl.itemClaims);
export default router;
